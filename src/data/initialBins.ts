import { BinRecord, ThresholdSettings } from '../types';

export const DEFAULT_THRESHOLDS: ThresholdSettings = {
  urgentMin: 90,
  highMin: 70,
  mediumMin: 40,
};

export const calculatePriority = (
  fillLevel: number,
  thresholds: ThresholdSettings = DEFAULT_THRESHOLDS
): 'Urgent' | 'High' | 'Medium' | 'Low' => {
  if (fillLevel >= thresholds.urgentMin) return 'Urgent';
  if (fillLevel >= thresholds.highMin) return 'High';
  if (fillLevel >= thresholds.mediumMin) return 'Medium';
  return 'Low';
};

export const calculateTimeToFull = (currentFill: number, hourlyRate: number): string => {
  if (currentFill >= 100) return 'Immediate (Full)';
  if (currentFill >= 95) return '15–20 minutes';
  if (hourlyRate <= 0) return '> 24 hours';
  
  const remaining = 100 - currentFill;
  const hoursRemaining = remaining / hourlyRate;

  if (hoursRemaining < 1) {
    const mins = Math.max(10, Math.round(hoursRemaining * 60));
    return `${mins} minutes`;
  }
  if (hoursRemaining < 2) {
    const mins = Math.round(hoursRemaining * 60);
    return `${Math.floor(hoursRemaining)}h ${mins % 60}m`;
  }
  if (hoursRemaining < 10) {
    return `${Math.round(hoursRemaining)} hours`;
  }
  return `${Math.round(hoursRemaining)} hours`;
};

